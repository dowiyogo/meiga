#!/usr/bin/env python3
"""Render a Geant4 VRML/WRL file with Blender.

Run from a normal shell through Blender, for example:

blender --background --python docs/beamer/render_wrl_with_blender.py -- \
  --input docs/beamer/figures/meiga_geometry_raw/g4_00.wrl \
  --output docs/beamer/figures/meiga_geometry_view.png
"""

from __future__ import annotations

import argparse
import math
import re
import sys
from pathlib import Path

import bpy
from mathutils import Vector


def parse_args() -> argparse.Namespace:
    argv = sys.argv
    if "--" in argv:
        argv = argv[argv.index("--") + 1 :]
    else:
        argv = []
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--input",
        default="docs/beamer/figures/meiga_geometry_raw/g4_00.wrl",
        help="Input WRL/X3D file",
    )
    parser.add_argument(
        "--output",
        default="docs/beamer/figures/meiga_geometry_view.png",
        help="Output PNG file",
    )
    return parser.parse_args(argv)


def clear_scene() -> None:
    bpy.ops.object.select_all(action="SELECT")
    bpy.ops.object.delete()


def import_wrl(path: Path) -> bool:
    text = path.read_text(encoding="utf-8", errors="replace")
    if "Generated by VRML 2.0 driver of GEANT4" in text:
        print("Detected Geant4 VRML output; using safe internal IndexedFaceSet parser.")
        return import_geant4_wrl(text)

    try:
        try:
            bpy.ops.preferences.addon_enable(module="io_scene_x3d")
        except Exception:
            pass
        bpy.ops.import_scene.x3d(filepath=str(path))
        return True
    except Exception as exc:  # noqa: BLE001
        print("Blender could not import WRL/X3D. The x3d importer may be unavailable.")
        print(f"Import error: {exc}")
        return False


def parse_float_triplets(block: str) -> list[tuple[float, float, float]]:
    values: list[tuple[float, float, float]] = []
    for line in block.splitlines():
        line = line.strip().rstrip(",")
        if not line:
            continue
        parts = line.split()
        if len(parts) < 3:
            continue
        try:
            values.append((float(parts[0]), float(parts[1]), float(parts[2])))
        except ValueError:
            continue
    return values


def parse_faces(block: str) -> list[list[int]]:
    faces: list[list[int]] = []
    current: list[int] = []
    for token in re.findall(r"-?\d+", block):
        value = int(token)
        if value == -1:
            if len(current) >= 3:
                faces.append(current)
            current = []
        else:
            current.append(value)
    if len(current) >= 3:
        faces.append(current)
    return faces


def material_for_shape(name: str, color: tuple[float, float, float], transparency: float) -> bpy.types.Material:
    mat = bpy.data.materials.new(name=f"{name}_mat")
    alpha = max(0.42, min(1.0, 1.0 - transparency))
    if name.startswith("LOWER_X") or name.startswith("UPPER_X"):
        color = (0.1, 0.55, 0.2)
    elif name.startswith("LOWER_Y") or name.startswith("UPPER_Y"):
        color = (0.2, 0.35, 0.85)
    mat.diffuse_color = (color[0], color[1], color[2], alpha)
    mat.use_nodes = True
    principled = mat.node_tree.nodes.get("Principled BSDF")
    if principled:
        principled.inputs["Base Color"].default_value = mat.diffuse_color
        principled.inputs["Alpha"].default_value = alpha
        principled.inputs["Roughness"].default_value = 0.55
    mat.blend_method = "BLEND"
    mat.use_screen_refraction = True
    return mat


def import_geant4_wrl(text: str) -> bool:
    imported = 0
    chunks = re.split(r"#---------- SOLID:\s*", text)
    for chunk in chunks[1:]:
        header, _, rest = chunk.partition("\n")
        name = header.strip().split(":")[0]
        if not name or name == "World":
            continue

        color_match = re.search(r"diffuseColor\s+([0-9eE+\-.]+)\s+([0-9eE+\-.]+)\s+([0-9eE+\-.]+)", rest)
        color = (0.35, 0.55, 0.78)
        if color_match:
            color = tuple(float(color_match.group(i)) for i in range(1, 4))  # type: ignore[assignment]
        transparency_match = re.search(r"transparency\s+([0-9eE+\-.]+)", rest)
        transparency = float(transparency_match.group(1)) if transparency_match else 0.0

        points_match = re.search(r"point\s*\[(.*?)\]", rest, flags=re.S)
        faces_match = re.search(r"coordIndex\s*\[(.*?)\]", rest, flags=re.S)
        if not points_match or not faces_match:
            continue

        vertices = parse_float_triplets(points_match.group(1))
        faces = parse_faces(faces_match.group(1))
        if not vertices or not faces:
            continue

        mesh = bpy.data.meshes.new(name=f"{name}_mesh")
        mesh.from_pydata(vertices, [], faces)
        mesh.update()
        obj = bpy.data.objects.new(name=name, object_data=mesh)
        bpy.context.collection.objects.link(obj)
        obj.data.materials.append(material_for_shape(name, color, transparency))
        imported += 1

    print(f"Imported {imported} Geant4 WRL solids.")
    return imported > 0


def scene_bbox() -> tuple[Vector, Vector] | None:
    coords: list[Vector] = []
    for obj in bpy.context.scene.objects:
        if obj.type not in {"MESH", "CURVE", "SURFACE", "FONT", "EMPTY"}:
            continue
        try:
            for corner in obj.bound_box:
                coords.append(obj.matrix_world @ Vector(corner))
        except Exception:
            continue
    if not coords:
        return None
    min_corner = Vector((min(v.x for v in coords), min(v.y for v in coords), min(v.z for v in coords)))
    max_corner = Vector((max(v.x for v in coords), max(v.y for v in coords), max(v.z for v in coords)))
    return min_corner, max_corner


def center_geometry(min_corner: Vector, max_corner: Vector) -> tuple[Vector, float]:
    center = 0.5 * (min_corner + max_corner)
    for obj in bpy.context.scene.objects:
        if obj.type in {"MESH", "CURVE", "SURFACE", "FONT", "EMPTY"}:
            obj.location -= center
    span = max((max_corner - min_corner).length, 1.0)
    return Vector((0.0, 0.0, 0.0)), span


def look_at(obj: bpy.types.Object, target: Vector) -> None:
    direction = target - obj.location
    obj.rotation_euler = direction.to_track_quat("-Z", "Y").to_euler()


def setup_camera_and_light(center: Vector, span: float) -> None:
    distance = max(span * 1.35, 80.0)
    cam_location = Vector((distance * 0.85, -distance * 1.05, distance * 0.65))
    bpy.ops.object.camera_add(location=cam_location)
    camera = bpy.context.object
    look_at(camera, center)
    camera.data.lens = 45
    camera.data.clip_end = max(distance * 8.0, 2000.0)
    bpy.context.scene.camera = camera

    bpy.ops.object.light_add(type="AREA", location=(distance * 0.15, -distance * 0.25, distance * 0.85))
    area = bpy.context.object
    area.name = "RenderAreaLight"
    area.data.energy = 650
    area.data.size = max(span * 0.65, 25.0)

    bpy.ops.object.light_add(type="SUN", location=(-distance, distance, distance))
    sun = bpy.context.object
    sun.name = "RenderSunLight"
    sun.data.energy = 1.6


def set_material_defaults() -> None:
    for obj in bpy.context.scene.objects:
        if obj.type != "MESH":
            continue
        obj.select_set(True)
        bpy.context.view_layer.objects.active = obj
        try:
            bpy.ops.object.shade_smooth()
        except Exception:
            pass
        obj.select_set(False)
        if obj.data.materials:
            continue
        mat = bpy.data.materials.new(name=f"{obj.name}_mat")
        mat.diffuse_color = (0.35, 0.55, 0.78, 1.0)
        obj.data.materials.append(mat)


def render(output_path: Path) -> None:
    output_path.parent.mkdir(parents=True, exist_ok=True)
    scene = bpy.context.scene
    scene.render.resolution_x = 1600
    scene.render.resolution_y = 1200
    scene.render.film_transparent = False
    scene.world.color = (1.0, 1.0, 1.0)

    try:
        scene.render.engine = "CYCLES"
        scene.cycles.device = "CPU"
        scene.cycles.samples = 64
    except Exception:
        scene.render.engine = "BLENDER_EEVEE"

    scene.render.image_settings.file_format = "PNG"
    scene.render.filepath = str(output_path)
    bpy.ops.render.render(write_still=True)


def main() -> int:
    args = parse_args()
    input_path = Path(args.input).resolve()
    output_path = Path(args.output).resolve()

    print(f"Input WRL/X3D: {input_path}")
    print(f"Output PNG: {output_path}")

    if not input_path.exists():
        print(f"Input file does not exist: {input_path}")
        return 0

    clear_scene()
    if not import_wrl(input_path):
        return 0

    bbox = scene_bbox()
    if bbox is None:
        print("No renderable geometry was found after import.")
        return 0

    center, span = center_geometry(*bbox)
    set_material_defaults()
    setup_camera_and_light(center, span)
    render(output_path)
    print(f"Rendered {output_path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
